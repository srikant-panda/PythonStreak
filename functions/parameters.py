# parameters:- is a variable wich plays as a role of placeholder of a value.

#Arguments:- The value user pass to function during call
def greet(name):            # name is parameter
    print('Hello',name)
greet('srikant')            # srikant is argument of the parameter
greet('Sumit')              #Sumit is argument


